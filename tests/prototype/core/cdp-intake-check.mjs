// 告訴 Zero 文件核對：真伺服器及 Chrome，所有測試資料放在輸出資料夾。
import fs from 'node:fs';
import path from 'node:path';
import { spawn } from 'node:child_process';
import { createRequire } from 'node:module';
import { openChrome, sleep } from '../lib/cdp-lib.mjs';
import { certifyDirect, usePass } from '../lib/testkit.mjs';

const [CHROME, OUT, PROTO, ADAPTER, PORT_ARG] = process.argv.slice(2);
const N = createRequire(import.meta.url)(path.join(PROTO, 'names.js'));
const PORT = Number(PORT_ARG), BASE = `http://127.0.0.1:${PORT}`, results = [];
const ok = (name, pass, info) => results.push({ name, pass: !!pass, info: pass ? undefined : info });
async function waitFor(fn, ms = 15000) { const end = Date.now() + ms; while (Date.now() < end) { const v = await fn(); if (v) return v; await sleep(150); } return null; }
fs.mkdirSync(OUT, { recursive: true });
const RUN = fs.mkdtempSync(path.join(OUT, 'intake-check-')), DATA = path.join(RUN, 'data');
fs.mkdirSync(DATA, { recursive: true });
const pdf = path.join(RUN, 'proposal_v3.pdf'), doc = path.join(RUN, '會議紀錄_1028.docx'), template = path.join(RUN, 'filled.md');
fs.writeFileSync(pdf, '虛構測試文件'); fs.writeFileSync(doc, '虛構測試文件');
fs.writeFileSync(template, '# 測試範本\n\n## 建議一併放入的文件\n\n清單：\n- `proposal_v3.pdf`：現行提案，載有收費資料。\n- **會議紀錄_1028.docx**：會面紀錄。\n- 市場研究簡報（Google Slides，請先下載成 PDF）\n\n---\n');
let server, chrome;
try {
  await certifyDirect(DATA, PROTO, ADAPTER);
  server = spawn(process.execPath, [path.join(PROTO, 'server.mjs'), '--port', String(PORT)], { cwd: PROTO, env: { ...process.env, SOS_DATA: DATA, SOS_ADAPTER: ADAPTER, SOS_NO_OPEN: '1' }, stdio: 'ignore', windowsHide: true });
  if (!await waitFor(async () => { try { return (await fetch(BASE + '/api/status')).status > 0; } catch { return false; } })) throw new Error('server did not start');
  chrome = await openChrome(CHROME, path.join(RUN, 'profile'), PORT + 1);
  await usePass(BASE, chrome);
  await chrome.go(BASE + '/#/intake');
  const ev = expression => chrome.ev(expression);
  if (!await waitFor(() => ev(`!!document.querySelector('#q1')`))) throw new Error('intake form did not appear');
  const text = sel => ev(`document.querySelector(${JSON.stringify(sel)})?.innerText || ''`);
  const set = async (sel, value) => { await ev(`(()=>{const e=document.querySelector(${JSON.stringify(sel)});e.value=${JSON.stringify(value)};e.dispatchEvent(new Event('input',{bubbles:true}))})()`); };
  const attach = async files => {
    const root = await chrome.send('DOM.getDocument', { depth: -1 });
    const input = await chrome.send('DOM.querySelector', { nodeId: root.root.nodeId, selector: '#intake-files' });
    await chrome.send('DOM.setFileInputFiles', { nodeId: input.nodeId, files });
    await sleep(200);
  };
  const remove = name => ev(`(()=>{const row=[...document.querySelectorAll('#file-list .file-row')].find(e=>e.firstElementChild.textContent===${JSON.stringify(name)});if(!row)throw Error('file row missing');row.querySelector('button').click()})()`);
  ok('沒有文件或連結時沒有提示', await ev(`document.querySelector('#doc-check').hidden && [...document.querySelectorAll('[id^="q-warn-"]')].every(e=>e.hidden)`));
  await set('#q4', '請參閱 https://docs.google.com/presentation/d/x/edit');
  ok('Google 文件連結提示', (await text('#q-warn-4')).includes(N.ui.checkLinkGoogle), await text('#q-warn-4'));
  ok('提示有類型字和隱藏的標記', (await text('#q-warn-4')).includes(N.ui.noteWarn + '：') && await ev(`document.querySelector('#q-warn-4 .note-mark').getAttribute('aria-hidden') === 'true'`));
  await ev(`document.documentElement.setAttribute('data-marks','emoji')`);
  ok('emoji 模式保留類型字', await ev(`getComputedStyle(document.querySelector('#q-warn-4 .note-emoji')).display !== 'none' && document.querySelector('#q-warn-4 .note-emoji').textContent === '⚠️'`) && (await text('#q-warn-4')).includes(N.ui.noteWarn + '：'));
  await ev(`document.documentElement.setAttribute('data-marks','icon')`);
  await ev(`(()=>{const f=new File(['x'],'invalid.exe');const d=new DataTransfer();d.items.add(f);const e=document.querySelector('#intake-files');e.files=d.files;e.dispatchEvent(new Event('change',{bubbles:true}));})()`);
  ok('文件錯誤含類型字並提示讀屏', (await text('#intake-err')).includes(N.ui.noteError + '：') && await ev(`document.querySelector('#intake-err [role="alert"] .note-mark').getAttribute('aria-hidden') === 'true'`));
  await set('#q4', '已刪去連結');
  ok('移除連結後提示消失', await ev(`document.querySelector('#q-warn-4').hidden`));
  await set('#q4', '請參閱 https://www.dropbox.com/s/x');
  ok('Dropbox 網上文件提示', (await text('#q-warn-4')).includes(N.ui.checkLinkOnline), await text('#q-warn-4'));
  await set('#q6', '詳見 D:\\公司\\proposal_v3.pdf');
  ok('路徑只顯示未加入的檔名', (await text('#q-warn-6')).includes(N.t('checkFileMissing', { f: 'proposal_v3.pdf' })), await text('#q-warn-6'));
  await attach([pdf]);
  ok('加入所提文件後提示消失', await ev(`document.querySelector('#q-warn-6').hidden`));
  await attach([template]);
  const expected = N.t('checkListCount', { n: 2, k: 1, f: '會議紀錄_1028.docx' });
  await waitFor(async () => (await text('#doc-check')).includes(expected));
  let check = await text('#doc-check');
  ok('範本數目、未加入檔名及無檔名項目', check.includes(expected) && check.includes('會議紀錄_1028.docx') && check.includes(N.t('checkListNoName', { f: '市場研究簡報（Google Slides，請先下載成 PDF）' })), check);
  await chrome.shot(path.join(OUT, 'intake-check-1440.png'), '#intake-form');
  await chrome.send('Emulation.setDeviceMetricsOverride', { width: 390, height: 844, deviceScaleFactor: 1, mobile: true });
  ok('390px 沒有橫向捲動', await ev(`document.documentElement.scrollWidth <= innerWidth`), await ev(`({scrollWidth:document.documentElement.scrollWidth,innerWidth})`));
  // 以全頁截圖保留文件清單與題目提示。
  const height = await ev('document.documentElement.scrollHeight');
  await chrome.send('Emulation.setDeviceMetricsOverride', { width: 390, height: Math.min(height, 16000), deviceScaleFactor: 1, mobile: true });
  const image = await chrome.send('Page.captureScreenshot', { format: 'png', captureBeyondViewport: true });
  fs.writeFileSync(path.join(OUT, 'intake-check-390.png'), Buffer.from(image.data, 'base64'));
  await chrome.send('Emulation.setDeviceMetricsOverride', { width: 1440, height: 900, deviceScaleFactor: 1, mobile: false });
  await attach([doc]);
  check = await text('#doc-check');
  ok('範本所列文件全部加入', check.includes(N.t('checkListAll', { n: 2 })), check);
  await remove('會議紀錄_1028.docx');
  await set('#q1', '我們提供服務');
  await ev(`document.querySelector('#intake-go').click()`);
  const modal = await text('#intake-confirm-missing');
  ok('提交前顯示未加入文件，但確認按鈕可按', modal.includes('會議紀錄_1028.docx') && await ev(`!document.querySelector('#intake-confirm').disabled`), modal);
  await ev(`document.querySelector('.m-foot button').click()`);
  await set('#q1', 'README.md');
  const once = await text('#q-warn-1');
  ok('第 1 題檔名只提示一次', once.includes(N.t('checkFileMissing', { f: 'README.md' })) && await ev(`document.querySelector('#q-warn-1').children.length===1`), once);
  await ev(`document.querySelector('#intake-go').click()`);
  const both = await text('#intake-confirm-missing');
  ok('確認框合併答案及清單的缺少文件', both.includes('README.md') && both.includes('會議紀錄_1028.docx'), both);
} catch (error) { ok('驗收中斷', false, String(error.stack || error)); }
ok('頁面沒有程式錯誤', !!chrome && !chrome.errors.length, chrome?.errors);
chrome?.close(); server?.kill();
for (const r of results) console.log((r.pass ? 'PASS ' : 'FAIL ') + r.name + (r.pass ? '' : '\n' + JSON.stringify(r.info ?? null)));
console.log(`\n${results.filter(r => r.pass).length}/${results.length} passed`);
process.exitCode = results.every(r => r.pass) ? 0 : 1;
